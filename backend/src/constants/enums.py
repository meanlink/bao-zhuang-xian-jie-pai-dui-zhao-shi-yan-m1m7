from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class ReviewGroupStatus(str, Enum):
    draft = 'draft'
    locked = 'locked'
    running = 'running'
    computed = 'computed'
    failed = 'failed'
    approved = 'approved'
    published = 'published'
class ReviewItemStatus(str, Enum):
    pending = 'pending'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
